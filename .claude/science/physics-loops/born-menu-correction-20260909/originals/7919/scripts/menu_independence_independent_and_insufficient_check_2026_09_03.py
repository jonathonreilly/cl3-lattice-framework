def popcount(n):
    return bin(n).count("1")


class Pauli:
    """i^k prod_q X_q^{x_q} Z_q^{z_q}, X before Z on every qubit."""

    __slots__ = ("k", "x", "z")

    def __init__(self, k, x, z):
        self.k = k % 4
        self.x = x
        self.z = z

    def __mul__(self, other):
        return Pauli(self.k + other.k + 2 * popcount(self.z & other.x), self.x ^ other.x, self.z ^ other.z)

    def neg(self):
        return Pauli(self.k + 2, self.x, self.z)

    def __eq__(self, other):
        return self.k == other.k and self.x == other.x and self.z == other.z

    def __hash__(self):
        return hash((self.k, self.x, self.z))


PHASE = (1 + 0j, 1j, -1 + 0j, -1j)


def act(p, b):
    return b ^ p.x, PHASE[p.k] * ((-1) ** (popcount(p.z & b) % 2))


class Cube:
    """The 2x2x2 cube with 12 edge qubits in the superfast encoding, route-B convention."""

    def __init__(self):
        self.V = 8
        self.EDGES = sorted((min(s, s ^ bit), max(s, s ^ bit))
                            for s in range(8) for bit in (4, 2, 1) if s ^ bit > s)
        self.NQ = len(self.EDGES)
        self.DIM = 1 << self.NQ
        self.EIDX = {}
        for q, (i, j) in enumerate(self.EDGES):
            self.EIDX[(i, j)] = q
            self.EIDX[(j, i)] = q
        self.NBR = {i: sorted(j for (a, b) in self.EDGES for j in ((b,) if a == i else ((a,) if b == i else ())))
                    for i in range(self.V)}
        self.STARMASK = {i: sum(1 << self.EIDX[(i, k)] for k in self.NBR[i]) for i in range(self.V)}
        self.FACES = []
        for ax in range(3):
            bits = [4, 2, 1]
            fb = bits[ax]
            ob = [b for b in bits if b != fb]
            for val in (0, fb):
                self.FACES.append((val, val | ob[1], val | ob[0] | ob[1], val | ob[0]))

    def A_unsigned(self, i, j):
        x = 1 << self.EIDX[(i, j)]
        z = 0
        for k in self.NBR[i]:
            if k != j and k < j:
                z ^= 1 << self.EIDX[(i, k)]
        for l in self.NBR[j]:
            if l != i and l < i:
                z ^= 1 << self.EIDX[(j, l)]
        return Pauli(popcount(x & z) % 2, x, z)

    def A(self, i, j):
        p = self.A_unsigned(i, j)
        return p if i < j else p.neg()

    def B(self, i):
        return Pauli(0, 0, self.STARMASK[i])

    def loop(self, cyc):
        out = Pauli(0, 0, 0)
        for a in range(len(cyc)):
            out = out * self.A(cyc[a], cyc[(a + 1) % len(cyc)])
        return out

    def record(self, z):
        return tuple(popcount(z & self.STARMASK[i]) % 2 for i in range(self.V))

    def hop_pauli(self, i, j):
        a = self.A(i, j)
        return a * self.B(i), a * self.B(j)

    def hop_amp(self, p1, p2, y):
        b1, a1 = act(p1, y)
        b2, a2 = act(p2, y)
        assert b1 == b2
        v = 0.5j * (a1 - a2)
        return b1, complex(round(v.real), round(v.imag))


def build_cube():
    cube = Cube()
    stab = [cube.loop(f) for f in cube.FACES]
    gens, basis = [], []
    for s in stab:
        v = s.x
        for b in basis:
            v = min(v, v ^ b)
        if v:
            basis.append(v)
            basis.sort(reverse=True)
            gens.append(s)
    group = []
    for m in range(1 << len(gens)):
        p = Pauli(0, 0, 0)
        for t in range(len(gens)):
            if (m >> t) & 1:
                p = p * gens[t]
        group.append(p)
    dim = cube.DIM
    cid = -np.ones(dim, dtype=np.int64)
    phi = np.zeros(dim, dtype=complex)
    reps = []
    for z0 in range(dim):
        if cid[z0] >= 0:
            continue
        c = len(reps)
        reps.append(z0)
        for g in group:
            b, a = act(g, z0)
            cid[b] = c
            phi[b] = a

    def corner_xyz(s):
        return ((s >> 2) & 1, (s >> 1) & 1, s & 1)

    def eta_ks(v, a):
        if a == 0:
            return 1
        if a == 1:
            return -1 if (v[0] & 1) else 1
        return -1 if ((v[0] + v[1]) & 1) else 1

    eta = np.zeros(cube.NQ, dtype=np.int64)
    for q, (i, j) in enumerate(cube.EDGES):
        lo, hi = min(i, j), max(i, j)
        eta[q] = eta_ks(corner_xyz(lo), {4: 0, 2: 1, 1: 2}[lo ^ hi])
    flux = []
    for cyc in cube.FACES:
        f = 1
        for t in range(4):
            f *= int(eta[cube.EIDX[(cyc[t], cyc[(t + 1) % 4])]])
        flux.append(f)

    hamp = np.zeros((cube.NQ, dim), dtype=np.complex128)
    for q, e in enumerate(cube.EDGES):
        p1, p2 = cube.hop_pauli(*e)
        for z in range(dim):
            zz, amp = cube.hop_amp(p1, p2, z)
            if amp == 0:
                continue
            assert zz == z ^ (1 << q)
            hamp[q, z] = -1.0 * eta[q] * amp
    nval = np.array([sum(cube.record(z)) for z in range(dim)], dtype=np.int64)

    ncoset = len(reps)
    w = np.zeros((dim, ncoset), dtype=np.complex128)
    w[np.arange(dim), cid] = phi / np.sqrt(float(len(group)))
    hw = np.zeros((dim, ncoset), dtype=np.complex128)
    for c in range(ncoset):
        psi = w[:, c]
        out = np.zeros(dim, dtype=np.complex128)
        for q in range(cube.NQ):
            out[np.arange(dim) ^ (1 << q)] += hamp[q] * psi
        hw[:, c] = out
    hc = w.conj().T @ hw
    evals, evecs = np.linalg.eigh(hc)
    sea = w @ evecs[:, 0]
    return cube, hamp, nval, np.abs(sea) ** 2, float(evals[0]), float(evals[1] - evals[0]), \
        int(np.sum(evals < evals[0] + 1e-9)), flux, ncoset


def block_ground_diag(cube, hamp, nval, rmask, wval):
    """Ground-space diagonal of H restricted to a record block, split by the conserved N."""
    dim = cube.DIM
    idx = np.flatnonzero((np.arange(dim) & rmask) == wval)
    free = [q for q in range(cube.NQ) if not (rmask >> q) & 1]
    loc = -np.ones(dim, dtype=np.int64)
    blocks = []
    for n in np.unique(nval[idx]):
        sub = idx[nval[idx] == n]
        d = len(sub)
        loc[sub] = np.arange(d)
        hb = np.zeros((d, d), dtype=np.complex128)
        cols = np.arange(d)
        for q in free:
            a = hamp[q][sub]
            mask = a != 0
            if not mask.any():
                continue
            hb[loc[sub[mask] ^ (1 << q)], cols[mask]] += a[mask]
        loc[sub] = -1
        ev, vc = np.linalg.eigh(hb)
        blocks.append((sub, ev, vc))
    e0 = min(float(b[1][0]) for b in blocks)
    diag = np.zeros(dim)
    deg = 0
    for sub, ev, vc in blocks:
        sel = np.flatnonzero(ev < e0 + TOL)
        if len(sel) == 0:
            continue
        deg += len(sel)
        diag[sub] += np.sum(np.abs(vc[:, sel]) ** 2, axis=1)
    return e0, deg, diag / deg


def conditional_odds(prob, nq, max_k):
    """For every record set R with |R| <= max_k and every free edge q, the odds p(Z_q = 0)."""
    tensor = prob.reshape((2,) * nq)
    by_k = {k: {"values": set(), "menus": set(), "singletons": 0, "witness": None} for k in range(max_k + 1)}
    blocks = {k: 0 for k in range(max_k + 1)}
    for m in range(0, max_k + 2):
        for subset in itertools.combinations(range(nq), m):
            keep = sorted(nq - 1 - q for q in subset)
            drop = tuple(a for a in range(nq) if a not in set(keep))
            marg = tensor.sum(axis=drop) if drop else tensor
            qs = sorted(subset, reverse=True)
            if m <= max_k:
                blocks[m] += int(np.count_nonzero(marg > TOL))
            if m == 0:
                continue
            k = m - 1
            if k > max_k:
                continue
            for pos, q in enumerate(qs):
                flat = np.moveaxis(marg, pos, -1).reshape(-1, 2)
                tot = flat.sum(axis=1)
                good = tot > TOL
                p0 = flat[good, 0] / tot[good]
                rec = by_k[k]
                for v in np.unique(np.round(p0, 9)):
                    rec["values"].add(float(v))
                menu0 = p0 > 1e-12
                menu1 = (1.0 - p0) > 1e-12
                if np.any(menu0 & menu1):
                    rec["menus"].add((0, 1))
                if np.any(~menu0):
                    rec["menus"].add((1,))
                if np.any(~menu1):
                    rec["menus"].add((0,))
                single = int(np.count_nonzero(~menu0 | ~menu1))
                rec["singletons"] += single
                if single and rec["witness"] is None:
                    rows = np.flatnonzero(good)[np.flatnonzero(~menu0 | ~menu1)]
                    others = [x for x in qs if x != q]
                    row = int(rows[0])
                    bits = {}
                    for pos2, q2 in enumerate(others):
                        bits[q2] = (row >> (len(others) - 1 - pos2)) & 1
                    rec["witness"] = (tuple(sorted(bits)), tuple(bits[b] for b in sorted(bits)), q,
                                      float(p0[np.flatnonzero(~menu0 | ~menu1)][0]))
    return by_k, blocks


