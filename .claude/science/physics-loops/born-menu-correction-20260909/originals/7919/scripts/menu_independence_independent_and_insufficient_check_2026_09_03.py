def t1_torus(checks):
    """Deterministic 3^3 torus: translation and rotation covariance of the menu key."""
    L = 3
    sites = [(x, y, z) for x in range(L) for y in range(L) for z in range(L)]
    index = {s: i for i, s in enumerate(sites)}
    nbr = np.array([[index[tuple((s[a] + DIRS[j][a]) % L for a in range(3))] for j in range(6)]
                    for s in sites], dtype=np.int64)
    ncfg = 400
    conf = np.array([[(11 * c + 5 * s + 3 * c * s + 1) % 7 for s in range(27)] for c in range(ncfg)],
                    dtype=np.int8)

    def keys(cfg):
        picked = cfg[:, nbr]                      # (ncfg, 27, 6)
        return SYMVEC[picked].sum(axis=2).astype(np.int64), (picked != 0).sum(axis=2).astype(np.int64)

    v0, k0 = keys(conf)
    tmis = 0
    tchecks = 0
    for t in sites:
        perm = np.array([index[tuple((s[a] - t[a]) % L for a in range(3))] for s in sites])
        shifted = conf[:, perm]
        v1, k1 = keys(shifted)
        target = np.array([index[tuple((s[a] + t[a]) % L for a in range(3))] for s in sites])
        tmis += int(np.count_nonzero(np.any(v1[:, target] != v0, axis=2) | (k1[:, target] != k0)))
        tchecks += ncfg * len(sites)
    checks.check(
        "T1-torus-translation",
        f"on a 3^3 torus the menu key is translation covariant over {tchecks} checks",
        tchecks == 291600 and tmis == 0,
    )
    rmis = 0
    rchecks = 0
    for rot in ROTS:
        sigma, _ = symbol_map(rot)
        inv = np.linalg.inv(rot).round().astype(np.int64)
        src = np.array([index[tuple(int(v) % L for v in inv @ np.array(s, dtype=np.int64))] for s in sites])
        tgt = np.array([index[tuple(int(v) % L for v in rot @ np.array(s, dtype=np.int64))] for s in sites])
        rotated = sigma[conf[:, src]]
        v1, k1 = keys(rotated)
        expect = v0 @ rot.T
        rmis += int(np.count_nonzero(np.any(v1[:, tgt] != expect, axis=2) | (k1[:, tgt] != k0)))
        rchecks += ncfg * len(sites)
    checks.check(
        "T1-torus-rotation",
        f"the menu key is rotation covariant about the origin over {rchecks} checks",
        rchecks == 259200 and rmis == 0,
    )


