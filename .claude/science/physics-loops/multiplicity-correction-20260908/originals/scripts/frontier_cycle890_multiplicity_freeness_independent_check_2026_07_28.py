def rref(rows):
    m = [[Fraction(x) for x in r] for r in rows]
    if not m or not m[0]:
        return [], []
    w = len(m[0])
    piv, rank = [], 0
    for col in range(w):
        p = None
        for r in range(rank, len(m)):
            if m[r][col] != 0:
                p = r
                break
        if p is None:
            continue
        m[rank], m[p] = m[p], m[rank]
        h = m[rank][col]
        m[rank] = [x / h for x in m[rank]]
        for r in range(len(m)):
            if r != rank and m[r][col] != 0:
                f = m[r][col]
                m[r] = [a - f * b for a, b in zip(m[r], m[rank])]
        piv.append(col)
        rank += 1
    return m[:rank], piv


def rank_exact(rows) -> int:
    return len(rref(rows)[0])


def key_of(rows) -> tuple:
    reduced, _ = rref(rows)
    return tuple(tuple(f"{x.numerator}/{x.denominator}" for x in row)
                 for row in reduced)


