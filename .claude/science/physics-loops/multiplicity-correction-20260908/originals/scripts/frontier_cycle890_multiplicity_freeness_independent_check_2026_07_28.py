def pins_certificate() -> dict:
    rows, ok = [], True
    for path in AUDIT_INPUT_PATHS:
        target = ROOT / path
        exists = target.exists()
        got = sha256(_read_bytes(path)).hexdigest() if exists else None
        try:
            blob = subprocess.run(["git", "hash-object", str(target)],
                                  capture_output=True, text=True,
                                  cwd=str(ROOT), check=True).stdout.strip() \
                if exists else None
        except Exception:                              # pragma: no cover gate
            blob = None
        expected_sha = EXPECTED_SHA256.get(path)
        expected_blob = EXPECTED_GIT_BLOBS.get(path)
        sha_ok = expected_sha is None or got == expected_sha
        blob_ok = expected_blob is None or blob == expected_blob
        ok = ok and exists and sha_ok and blob_ok
        rows.append({"path": path, "exists": exists, "sha256": got,
                     "sha256_matches_pin": sha_ok, "git_blob": blob,
                     "git_blob_matches_pin": blob_ok,
                     "pinned_by_value": expected_sha is not None})
    return {
        "statement": (
            "Pins. The four swept documents and the 888 receipt are pinned by "
            "SHA-256 and git blob; the 890 primary and its receipt are read as "
            "TEXT/JSON evidence under attack, so their hashes are recorded "
            "rather than pre-pinned -- a checker that pinned the artifact it "
            "is auditing would be checking its own copy."
        ),
        "rows": rows,
        "firewall_hits": FIREWALL.hits,
        "finding": f"{sum(1 for r in rows if r['exists'])}/{len(rows)} inputs "
                   f"present; "
                   f"{sum(1 for r in rows if r['pinned_by_value'] and r['sha256_matches_pin'] and r['git_blob_matches_pin'])}"
                   f"/{sum(1 for r in rows if r['pinned_by_value'])} value-pinned "
                   f"inputs round-trip.",
        "pass": ok,
    }


