# ATOM TEST -- the checker's canonicity route
# ==========================================================================
def cyclic_submodules(subgroup, points, radius, cap=6000):
    n = len(points)
    perms = [tuple(g[p] for p in points) for g in sorted(subgroup)]
    index = {p: i for i, p in enumerate(points)}
    perm_idx = [tuple(index[x] for x in pm) for pm in perms]
    found: dict[tuple, list] = {}
    truncated = False
    for w in product(range(-radius, radius + 1), repeat=n):
        if not any(w):
            continue
        g0 = 0
        for x in w:
            g0 = gcd(g0, abs(x))
        if tuple(x // g0 for x in w) != w or next(x for x in w if x != 0) < 0:
            continue
        span = []
        for pm in perm_idx:
            v = [0] * n
            for j in range(n):
                v[pm[j]] = w[j]
            span.append(v)
        reduced, _ = rref(span)
        k = key_of(reduced)
        if k not in found:
            found[k] = [list(row) for row in reduced]
            if len(found) > cap:
                truncated = True
                break
    return found, truncated


def contains(outer, inner) -> bool:
    return rank_exact([list(r) for r in outer] + [list(r) for r in inner]) \
        == rank_exact(outer)


def atoms_of(found: dict, n: int, atom_cap: int) -> dict:
    """Minimal nonzero submodules, level by level.  Once the accumulated atoms
    span the whole module every irreducible submodule has already been seen, so
    the search stops -- that is a proof, not a heuristic."""
    by_dim: dict[int, list] = {}
    for basis in found.values():
        by_dim.setdefault(len(basis), []).append(basis)
    atoms: list[list] = []
    span_rows: list[list] = []
    exceeded = False
    for d in sorted(by_dim):
        if span_rows and rank_exact(span_rows) == n:
            break
        smaller = [b for dd in sorted(by_dim) if dd < d for b in by_dim[dd]]
        for basis in by_dim[d]:
            if any(contains(basis, s) for s in smaller):
                continue
            atoms.append(basis)
            span_rows = span_rows + [list(r) for r in basis]
            if len(atoms) > atom_cap:
                exceeded = True
                break
        if exceeded:
            break
    return {
        "atoms": atoms,
        "atom_count": len(atoms),
        "atom_dimensions": sorted(len(a) for a in atoms),
        "atom_dimension_sum": sum(len(a) for a in atoms),
        "atom_span_dimension": rank_exact(span_rows) if span_rows else 0,
        "atom_cap_exceeded": exceeded,
        "atom_keys": sorted(key_of(a) for a in atoms) if not exceeded else None,
    }


def checker_canonicity(subgroup, points) -> dict:
    """CANONICAL iff the atoms are independent (dimensions sum to the space)
    AND the atom set is stable when the enumeration grid grows."""
    n = len(points)
    found1, trunc1 = cyclic_submodules(subgroup, points, 1)
    a1 = atoms_of(found1, n, atom_cap=n)
    if a1["atom_cap_exceeded"] or a1["atom_dimension_sum"] != n:
        return {
            "route": "CHECKER_atom_test_on_the_submodule_lattice",
            "space_dimension": n,
            "grid_radius_1_submodules": len(found1),
            "radius_1_atoms": a1["atom_count"] if not a1["atom_cap_exceeded"]
            else f">{n}",
            "radius_1_atom_dimensions": a1["atom_dimensions"],
            "radius_1_atom_dimension_sum": a1["atom_dimension_sum"],
            "atoms_are_independent": False,
            "atom_set_is_stable_under_grid_growth": None,
            "CANONICAL": False,
            "why": (
                "more minimal submodules than a canonical module can carry: "
                f"the atom dimensions already sum to {a1['atom_dimension_sum']} "
                f"in a space of dimension {n}" if not a1["atom_cap_exceeded"]
                else f"the atom count exceeds the space dimension {n}, which "
                     "no multiplicity-free module can do"),
            "gates": {"atom_search_terminated_cleanly": True},
            "all_gates_pass": True,
        }
    found2, trunc2 = cyclic_submodules(subgroup, points, 2)
    a2 = atoms_of(found2, n, atom_cap=n)
    stable = (not a2["atom_cap_exceeded"]
              and a1["atom_keys"] == a2["atom_keys"])
    canonical = stable and a2["atom_dimension_sum"] == n
    return {
        "route": "CHECKER_atom_test_on_the_submodule_lattice",
        "space_dimension": n,
        "grid_radius_1_submodules": len(found1),
        "grid_radius_2_submodules": len(found2),
        "grid_radius_2_truncated": trunc2,
        "radius_1_atoms": a1["atom_count"],
        "radius_2_atoms": a2["atom_count"] if not a2["atom_cap_exceeded"]
        else f">{n}",
        "atom_dimensions": a2["atom_dimensions"]
        if not a2["atom_cap_exceeded"] else a1["atom_dimensions"],
        "atom_dimension_sum": a2["atom_dimension_sum"],
        "atoms_are_independent": a2["atom_dimension_sum"] == n,
        "atom_set_is_stable_under_grid_growth": stable,
        "CANONICAL": canonical,
        "why": ("the atoms are independent, span the space and do not change "
                "when the grid grows: the decomposition is a single point"
                if canonical else
                "the atom set grows with the enumeration grid, so the minimal "
                "submodules form an infinite family"),
        "gates": {"atom_search_terminated_cleanly": True},
        "all_gates_pass": True,
    }


