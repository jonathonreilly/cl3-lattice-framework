def build_checker_table() -> list[dict]:
    rows = []
    for c in CLASSES:
        h = sorted(c["key"])
        orbs = orbits_of(h, SHELL)
        free = [o for o in orbs if len(o) == c["order"]]
        scopes = {
            "ORBIT_SCOPE_maximal_free_orbit":
                sorted(max(free, key=len)) if free else None,
            "SHELL_SCOPE_whole_neighbourhood": list(SHELL),
        }
        entry = {
            "class": primary_name(c),
            "order": c["order"],
            "shell_orbit_lengths": c["shell_orbit_lengths"],
            "has_a_free_orbit": bool(free),
            "maximal_FREE_orbit_length":
                max([len(o) for o in free], default=0),
            "scopes": {},
        }
        for scope, points in scopes.items():
            if points is None:
                entry["scopes"][scope] = None
                continue
            entry["scopes"][scope] = {
                "space_dimension": len(points),
                "MULT_FREE": checker_multiplicity_free(h, points),
                "CANONICITY": checker_canonicity(h, points),
            }
        rows.append(entry)
    return rows


