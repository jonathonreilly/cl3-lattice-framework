# clause-level segmentation -- DIFFERENT from the primary's sentence level
# ==========================================================================
FENCE = re.compile(r"^\s*(```|~~~)")


def clause_segments(text: str) -> list[dict]:
    """Byte-exact partition at CLAUSE granularity: prose is cut at sentence
    terminators AND at semicolons, colons and em-dash breaks."""
    segments: list[dict] = []
    in_fence = False
    pos = 0
    for line in text.splitlines(keepends=True):
        start = pos
        pos += len(line)
        if FENCE.match(line):
            segments.append({"start": start, "text": line, "kind": "CODE"})
            in_fence = not in_fence
            continue
        if in_fence or not line.strip() or line.lstrip().startswith("|"):
            segments.append({"start": start, "text": line,
                             "kind": "CODE" if in_fence else "GAP"})
            continue
        if line.lstrip().startswith("#"):
            segments.append({"start": start, "text": line, "kind": "HEADING"})
            continue
        # cut inside the line
        cuts = []
        backticks = 0
        for i, ch in enumerate(line):
            if ch == "`":
                backticks += 1
                continue
            if backticks % 2 == 1:
                continue
            if ch in ";:":
                cuts.append(i + 1)
            elif ch in ".!?":
                nxt = line[i + 1] if i + 1 < len(line) else ""
                if nxt in ("", " ", "\n", "\t"):
                    cuts.append(i + 1)
            elif ch == "-" and line[i:i + 3] == " --":
                cuts.append(i)
        cuts.append(len(line))
        prev = 0
        for cut in sorted(set(c for c in cuts if 0 < c <= len(line))):
            if cut <= prev:
                continue
            piece = line[prev:cut]
            kind = "CLAUSE" if piece.strip() else "GAP"
            segments.append({"start": start + prev, "text": piece,
                             "kind": kind})
            prev = cut
        if prev < len(line):
            segments.append({"start": start + prev, "text": line[prev:],
                             "kind": "GAP"})
    return segments


