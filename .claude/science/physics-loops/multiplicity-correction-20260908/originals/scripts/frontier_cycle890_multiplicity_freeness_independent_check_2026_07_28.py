def checker_grade(text: str) -> dict:
    low = norm(text).lower()

    def hits(family):
        return sorted({m for m in family if m in low})

    r1 = hits(CHECKER_RUBRIC["R1_names_the_readout_object"])
    r2 = hits(CHECKER_RUBRIC["R2_asserts_no_freedom"])
    r3 = hits(CHECKER_RUBRIC["R3_names_the_decomposition_level"])
    r4 = hits(CHECKER_RUBRIC["R4_polarity_excludes"])
    if r4:
        grade = "NONE"
        reason = f"polarity {r4} places the content outside axiom supply"
    elif r1 and r2 and r3:
        grade = "EXACT"
        reason = (f"all three requirements fire in one clause: subject {r1}, "
                  f"no-freedom {r2}, decomposition level {r3}")
    elif sum(1 for x in (r1, r2, r3) if x) == 2:
        grade = "PARTIAL"
        reason = (f"two of three fire: subject {r1}, no-freedom {r2}, "
                  f"decomposition level {r3}")
    else:
        grade = "NONE"
        reason = (f"fewer than two requirements fire: subject {r1}, "
                  f"no-freedom {r2}, decomposition level {r3}")
    return {"grade": grade, "R1": r1, "R2": r2, "R3": r3,
            "R4_exclusions": r4, "reason": reason}


