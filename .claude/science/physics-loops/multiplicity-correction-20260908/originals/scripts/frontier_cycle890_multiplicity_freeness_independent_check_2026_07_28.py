def class_signature(h) -> tuple:
    """A name computed from invariants only -- never borrowed."""
    orbs = sorted(len(o) for o in orbits_of(sorted(h), SHELL))
    element_orders = sorted(perm_order(g) for g in h)
    cyclic = any(perm_closure((g,)) == h for g in h)
    abelian = all(compose(a, b) == compose(b, a) for a in h for b in h)
    return (len(h), tuple(orbs), tuple(element_orders), cyclic, abelian)


