def compose(a, b):
    """(a after b): the permutation sending i to a[b[i]]."""
    return tuple(a[b[i]] for i in range(6))


def perm_order(p) -> int:
    cur, k = p, 1
    while cur != IDENT6:
        cur = compose(cur, p)
        k += 1
        if k > 24:                                     # pragma: no cover gate
            raise AssertionError("not a finite permutation")
    return k


def perm_closure(seeds) -> frozenset:
    found = {IDENT6} | set(seeds)
    frontier = list(found)
    while frontier:
        cur = frontier.pop()
        for other in list(found):
            for prod in (compose(cur, other), compose(other, cur)):
                if prod not in found:
                    found.add(prod)
                    frontier.append(prod)
    return frozenset(found)


GROUP = sorted(perm_closure((R4Z, R3D)))
GROUP_SET = frozenset(GROUP)
INVERSE = {p: next(x for x in GROUP if compose(p, x) == IDENT6) for p in GROUP}
SHELL = tuple(range(6))


def orbits_of(subgroup, points) -> list[tuple]:
    seen, out = set(), []
    for p in points:
        if p in seen:
            continue
        orbit = {p}
        frontier = [p]
        while frontier:
            cur = frontier.pop()
            for g in subgroup:
                nxt = g[cur]
                if nxt not in orbit:
                    orbit.add(nxt)
                    frontier.append(nxt)
        seen |= orbit
        out.append(tuple(sorted(orbit)))
    return out


def all_subgroups() -> list[frozenset]:
    found = {frozenset({IDENT6})}
    for a in GROUP:
        for b in GROUP:
            found.add(perm_closure((a, b)))
    return sorted(found, key=lambda h: (len(h), sorted(h)))


