def main() -> int:
    started = monotonic()
    payload = build_payload()
    second = build_payload()
    deterministic = digest(payload) == digest(second)
    payload["deterministic_double_build"] = deterministic
    summary = summarize(payload)
    summary["deterministic_double_build"] = deterministic
    summary["elapsed_sec"] = round(monotonic() - started, 3)

    findings = []
    c = payload["certificates"]
    if not c["D_T1_ATTACK"]["T1_SURVIVES"]:
        findings.append("FIND-A: T1 does NOT survive independent "
                        "recomputation. See D_T1_ATTACK rows.")
    if not c["F_T3_ATTACK"]["T3_CORE_SURVIVES"]:
        findings.append(
            "FIND-B: T3's LOAD-BEARING subset does not survive the full "
            "reading matrix. Classes sneaking in: "
            f"{c['F_T3_ATTACK']['classes_that_sneak_in_to_the_LOAD_BEARING_subset_under_a_reading_the_primary_skipped']}")
    if not c["F_T3_ATTACK"]["peripheral_mismatched_subset_agrees"]:
        findings.append(
            "FIND-1 (completeness, not refutation): the primary's reading set "
            "is incomplete. Classes that enter the PERIPHERAL "
            "scope-mismatched subset but not the primary's version of it: "
            f"{c['F_T3_ATTACK']['classes_that_enter_only_the_PERIPHERAL_mismatched_subset']}"
            f", admitted by "
            f"{sorted({g['reading'] for g in c['F_T3_ATTACK']['the_readings_that_admit_them']})}"
            ". The load-bearing scope-coherent subset is unaffected.")
    if not c["G_H2_SEGMENTATION_ATTACK"]["VERDICT_IS_SEGMENTATION_INVARIANT"]:
        findings.append("FIND-C: the H2 verdict is NOT segmentation-invariant.")
    if c["G_H2_SEGMENTATION_ATTACK"]["closing_needle_scan"][
            "hits_in_the_axiom_memo"]:
        findings.append("FIND-D: the axiom memo contains closing vocabulary "
                        "the primary's rubric did not surface.")
    if not deterministic:
        findings.append("FIND-E: the checker is not deterministic.")
    if not findings:
        findings.append(
            "No refutation found. Every claim under attack survives "
            "recomputation on independent machinery: T1 by orbital-algebra "
            "commutativity and the submodule atom test, T3 by the full "
            "reading matrix over every scope/reading combination, H2 by a "
            "clause-level re-segmentation and a blunt needle scan.")
    summary["FINDINGS"] = findings

    RECEIPT.parent.mkdir(parents=True, exist_ok=True)
    RECEIPT.write_text(json.dumps(summary, indent=1, sort_keys=True,
                                  default=str) + "\n", encoding="utf-8")
    out = json.dumps(payload, indent=1, sort_keys=True, default=str)
    if len(out.encode("utf-8")) > STDOUT_LIMIT_BYTES:
        out = json.dumps(summary, indent=1, sort_keys=True, default=str)
    print(out)
    return 0                       # exit 0 whether or not the claims survive


def preflight() -> None:
    problems = []
    for path in AUDIT_INPUT_PATHS:
        target = ROOT / path
        if not target.exists():
            problems.append(f"{path}: MISSING")
            continue
        expected = EXPECTED_SHA256.get(path)
        if expected is None:
            continue
        got = sha256(target.read_bytes()).hexdigest()
        if got != expected:
            problems.append(f"{path}: sha256 {got} != {expected}")
        try:
            blob = subprocess.run(["git", "hash-object", str(target)],
                                  capture_output=True, text=True,
                                  cwd=str(ROOT), check=True).stdout.strip()
        except Exception as exc:                       # pragma: no cover gate
            problems.append(f"{path}: git hash-object failed ({exc})")
            continue
        if blob != EXPECTED_GIT_BLOBS[path]:
            problems.append(f"{path}: git blob {blob} != "
                            f"{EXPECTED_GIT_BLOBS[path]}")
    if problems:
        print("PREFLIGHT PIN FAILURE (exit 2):")
        for row in problems:
            print("  " + row)
        raise SystemExit(2)


if __name__ == "__main__":
    preflight()
    raise SystemExit(main())
