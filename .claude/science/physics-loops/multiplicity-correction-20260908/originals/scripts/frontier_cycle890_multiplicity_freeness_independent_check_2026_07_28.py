# ORBITAL (Schur) algebra -- the checker's multiplicity-freeness route
# ==========================================================================
def orbitals(subgroup, points) -> list[list[tuple]]:
    """Orbits of the subgroup on X x X."""
    seen, out = set(), []
    for a in points:
        for b in points:
            if (a, b) in seen:
                continue
            orbit = set()
            for g in subgroup:
                orbit.add((g[a], g[b]))
            seen |= orbit
            out.append(sorted(orbit))
    return out


def orbital_matrices(subgroup, points):
    idx = {p: i for i, p in enumerate(points)}
    n = len(points)
    mats = []
    for orb in orbitals(subgroup, points):
        m = [[0] * n for _ in range(n)]
        for a, b in orb:
            if a in idx and b in idx:
                m[idx[a]][idx[b]] = 1
        mats.append(m)
    return mats


def int_mat_mul(a, b):
    n, k, w = len(a), len(b), len(b[0])
    return [[sum(a[i][t] * b[t][j] for t in range(k)) for j in range(w)]
            for i in range(n)]


def perm_matrix(g, points):
    idx = {p: i for i, p in enumerate(points)}
    n = len(points)
    m = [[0] * n for _ in range(n)]
    for p in points:
        m[idx[g[p]]][idx[p]] = 1
    return m


def checker_multiplicity_free(subgroup, points) -> dict:
    """The permutation module is multiplicity-free over Q exactly when its
    commutant -- spanned by the orbital adjacency matrices -- is commutative."""
    n = len(points)
    mats = orbital_matrices(subgroup, points)
    r = len(mats)
    commuting = True
    witness = None
    for i in range(r):
        for j in range(i + 1, r):
            if int_mat_mul(mats[i], mats[j]) != int_mat_mul(mats[j], mats[i]):
                commuting = False
                if witness is None:
                    witness = [i, j]
    # safety: Burnside on points and on pairs, computed directly
    order = len(subgroup)
    fixed = [sum(1 for p in points if g[p] == p) for g in sorted(subgroup)]
    burnside_orbits = Fraction(sum(fixed), order)
    burnside_orbitals = Fraction(sum(f * f for f in fixed), order)
    direct_orbits = len(orbits_of(sorted(subgroup), points))
    # safety: the orbital matrices really do commute with the representation
    rho = [perm_matrix(g, points) for g in sorted(subgroup)]
    is_commutant = all(int_mat_mul(rg, m) == int_mat_mul(m, rg)
                       for m in mats for rg in rho)
    # safety: the orbital matrices sum to the all-ones matrix
    total = [[sum(m[i][j] for m in mats) for j in range(n)] for i in range(n)]
    partition = all(total[i][j] == 1 for i in range(n) for j in range(n))
    gates = {
        "burnside_orbit_count_matches_the_direct_count":
            burnside_orbits == direct_orbits,
        "burnside_orbital_count_matches_the_direct_count":
            burnside_orbitals == r,
        "every_orbital_matrix_commutes_with_the_representation": is_commutant,
        "the_orbital_matrices_partition_X_times_X": partition,
    }
    return {
        "route": "CHECKER_orbital_Schur_algebra_commutativity",
        "space_dimension": n,
        "orbital_count_equals_dim_of_the_commutant": r,
        "burnside_orbital_count": f"{burnside_orbitals.numerator}/"
                                  f"{burnside_orbitals.denominator}",
        "orbit_count": direct_orbits,
        "commutant_is_commutative": commuting,
        "first_noncommuting_orbital_pair": witness,
        "MULTIPLICITY_FREE": commuting,
        "coarse_ordered_pair": [direct_orbits, n - direct_orbits],
        "gates": gates,
        "all_gates_pass": all(gates.values()),
    }


